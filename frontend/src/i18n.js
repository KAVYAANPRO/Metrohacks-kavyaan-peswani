const DICT = { en, hi, gu }
const KEY = 'sv-lang'

function initialLang() {
  try {
    const v = localStorage.getItem(KEY)
    if (v && DICT[v]) return v
  } catch { /* storage blocked */ }
  return 'en'
}

const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m)) : s)
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : '')

const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(initialLang)

  useEffect(() => {
    document.documentElement.lang = lang
    try { localStorage.setItem(KEY, lang) } catch { /* storage blocked */ }
  }, [lang])

  const setLang = useCallback((l) => DICT[l] && setLangState(l), [])
  const t = useCallback((key, vars) => fill(DICT[lang][key] ?? en[key] ?? key, vars), [lang])
  // Translate an enum value (e.g. tx('zone', 'exit')); unknown values fall back to Capitalised raw value.
  const tx = useCallback((group, value) => {
    const k = `${group}.${value}`
    return DICT[lang][k] ?? en[k] ?? cap(String(value ?? ''))
  }, [lang])

  const value = useMemo(() => ({ lang, setLang, t, tx }), [lang, setLang, t, tx])
  return createElement(LangContext.Provider, { value }, children)
}

export function useLang() {
  return useContext(LangContext)
}
